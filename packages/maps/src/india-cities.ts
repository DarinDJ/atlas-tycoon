type Rent = PropertyTile['rent'];

interface CityInput {
  id: string;
  name: string;
  hi: string;
  group: string;
  price: number;
  rent: Rent;
  houseCost: number;
  emoji: string;
  fact: string;
  factHi: string;
  lat: number;
  lng: number;
}

function city(c: CityInput): PropertyTile {
  return {
    id: c.id,
    name: c.name,
    type: 'property',
    group: c.group,
    price: c.price,
    rent: c.rent,
    houseCost: c.houseCost,
    emoji: c.emoji,
    fact: c.fact,
    lat: c.lat,
    lng: c.lng,
    i18n: { hi: { name: c.hi, fact: c.factHi } },
  };
}

